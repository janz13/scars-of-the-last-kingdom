/**
 * Build-Time Story Metadata Generator — Scars of the Last Kingdom
 *
 * Scans STORY_NODES, ENDINGS, and SCENE_MANIFEST once at build time and emits
 * `artifacts/mobile/data/storyMetadata.generated.ts` so UI screens and validators
 * never duplicate hardcoded counts or pull the synchronous story graph into the
 * web entry bundle.
 *
 * Run with: pnpm run generate:metadata
 */

import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const require = createRequire(import.meta.url);
if (typeof require !== 'undefined' && (require as any).extensions) {
  (require as any).extensions['.png'] = () => ({});
  (require as any).extensions['.webp'] = () => ({});
  (require as any).extensions['.jpg'] = () => ({});
}

const { STORY_NODES } = require('../../artifacts/mobile/data/story/allNodesSync.ts');
const { ENDINGS } = require('../../artifacts/mobile/data/story/endings.ts');
const { SCENE_MANIFEST } = require('../../artifacts/mobile/constants/sceneManifest.ts');

const CHAPTER_ORDER = [
  'Prologue',
  'Chapter 1',
  'Chapter 2',
  'Chapter 3',
  'Chapter 4',
  'Chapter 5',
  'Chapter 6',
  'Chapter 7',
  'Chapter 8',
  'Chapter 9',
  'Chapter 10',
  'Chapter 11',
  'Chapter 12',
  'Final Chapter 1',
  'Final Chapter 2',
  'Epilogue',
] as const;

const DIRECT_ROADMAP_CHAPTER_TO_ID: Record<string, string> = {
  'Prologue': 'prologue',
  'Chapter 2': 'chapter_2',
  'Chapter 3': 'chapter_3',
  'Chapter 4': 'chapter_4',
  'Chapter 5': 'chapter_5',
  'Chapter 6': 'chapter_6',
  'Chapter 7': 'chapter_7',
  'Chapter 8': 'chapter_8',
  'Chapter 9': 'chapter_9',
  'Chapter 10': 'chapter_10',
  'Chapter 11': 'chapter_11',
  'Chapter 12': 'chapter_12',
  'Final Chapter 1': 'final_chapter_1',
  'Final Chapter 2': 'final_chapter_2',
  'Epilogue': 'epilogue',
};

export function generateStoryMetadata() {
  const totalNodes: number = STORY_NODES.length;
  const endingNodes: number = ENDINGS.length;
  const pixelSceneCount: number = Object.keys(SCENE_MANIFEST).length;

  let totalChoices = 0;
  let diceCheckNodes = 0;
  const chapterCounts: Record<string, number> = {};
  const chapterEndingCounts: Record<string, number> = {};

  for (const ch of CHAPTER_ORDER) {
    chapterCounts[ch] = 0;
  }

  for (const node of STORY_NODES) {
    const ch = String(node.chapter || 'Chapter 1');
    chapterCounts[ch] = (chapterCounts[ch] ?? 0) + 1;

    const choices = Array.isArray(node.choices) ? node.choices : [];
    totalChoices += choices.length;
    if (choices.some((c: any) => Boolean(c.diceCheck))) {
      diceCheckNodes++;
    }
  }

  for (const ending of ENDINGS) {
    const ch = String(ending.chapter || 'Chapter 1');
    chapterEndingCounts[ch] = (chapterEndingCounts[ch] ?? 0) + 1;
  }

  const roadmapNodeCounts: Record<string, number> = {
    prologue: 0,
    chapter_1: 0,
    chapter_2: 0,
    chapter_3: 0,
    chapter_4: 0,
    chapter_5: 0,
    chapter_6: 0,
    chapter_7: 0,
    chapter_8: 0,
    chapter_9: 0,
    chapter_10: 0,
    chapter_11: 0,
    chapter_12: 0,
    final_chapter_1: 0,
    final_chapter_2: 0,
    epilogue: 0,
  };

  for (const [chapterName, count] of Object.entries(chapterCounts)) {
    const mappedId = DIRECT_ROADMAP_CHAPTER_TO_ID[chapterName];
    if (mappedId) {
      roadmapNodeCounts[mappedId] += count;
    } else {
      // Fold Chapter 1 + auxiliary event/vision/interlude pools into chapter_1
      roadmapNodeCounts.chapter_1 += count;
    }
  }

  const roadmapSum = Object.values(roadmapNodeCounts).reduce((a, b) => a + b, 0);
  if (roadmapSum !== totalNodes) {
    throw new Error(
      `Roadmap node sum mismatch: expected ${totalNodes}, got ${roadmapSum}`
    );
  }

  const outPath = resolve(
    import.meta.dirname,
    '../../artifacts/mobile/data/storyMetadata.generated.ts'
  );

  const generatedContent = `// AUTO-GENERATED BY scripts/src/generateStoryMetadata.ts — DO NOT EDIT MANUALLY.
// Re-run via \`pnpm run generate:metadata\` after adding or removing story nodes or endings.

export interface GeneratedStorySummary {
  totalNodes: number;
  endingNodes: number;
  totalChoices: number;
  diceCheckNodes: number;
  pixelSceneCount: number;
  chapters: string[];
  chapterCounts: Record<string, number>;
  chapterEndingCounts: Record<string, number>;
}

export const GENERATED_STORY_SUMMARY: GeneratedStorySummary = ${JSON.stringify(
    {
      totalNodes,
      endingNodes,
      totalChoices,
      diceCheckNodes,
      pixelSceneCount,
      chapters: [...CHAPTER_ORDER],
      chapterCounts,
      chapterEndingCounts,
    },
    null,
    2
  )};

export const GENERATED_ROADMAP_NODE_COUNTS: Record<string, number> = ${JSON.stringify(
    roadmapNodeCounts,
    null,
    2
  )};
`;

  writeFileSync(outPath, generatedContent, 'utf-8');
  console.log(
    `✅ Generated story metadata -> artifacts/mobile/data/storyMetadata.generated.ts ` +
      `(${totalNodes} nodes, ${endingNodes} endings, ${totalChoices} choices, ${diceCheckNodes} dice nodes, ${pixelSceneCount} pixel scenes)`
  );
}

const isDirectCli =
  import.meta.url === `file://${process.argv[1]?.replace(/\\/g, '/')}` ||
  process.argv[1]?.endsWith('generateStoryMetadata.ts');

if (isDirectCli) {
  generateStoryMetadata();
}
